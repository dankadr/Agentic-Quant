"""Research documents: a logical document, its immutable versions, and their extracted pages."""

from datetime import datetime
from decimal import Decimal
from typing import Any
from uuid import UUID, uuid4

from sqlalchemy import Computed, ForeignKey
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from trading.db.base import Base


class ResearchDocumentRow(Base):
    __tablename__ = "research_documents"
    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    logical_key: Mapped[str] = mapped_column(unique=True)
    category: Mapped[str]
    company: Mapped[str | None]
    title: Mapped[str]
    created_at: Mapped[datetime]


class DocumentVersionRow(Base):
    __tablename__ = "document_versions"
    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    document_id: Mapped[UUID] = mapped_column(ForeignKey("research_documents.id"))
    version_no: Mapped[int]
    sha256: Mapped[str] = mapped_column(unique=True)
    byte_size: Mapped[int]
    content_type: Mapped[str]
    origin: Mapped[str]
    source: Mapped[str]
    source_url: Mapped[str | None]
    published_at: Mapped[datetime | None]  # when the SOURCE says it was published
    retrieved_at: Mapped[datetime]  # when THIS system obtained these exact bytes
    reporting_period: Mapped[str | None]
    access: Mapped[str]
    extraction_status: Mapped[str]
    extraction_error: Mapped[str | None]
    amendment_of: Mapped[UUID | None] = mapped_column(ForeignKey("document_versions.id"))


class DocumentPageRow(Base):
    __tablename__ = "document_pages"
    version_id: Mapped[UUID] = mapped_column(ForeignKey("document_versions.id"), primary_key=True)
    page: Mapped[int] = mapped_column(primary_key=True)
    text: Mapped[str]
    # Generated by PostgreSQL from ``text``; mapped so the schema check sees it, never written here.
    tsv: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', text)", persisted=True), nullable=True
    )


class ResearchReportRow(Base):
    __tablename__ = "research_reports"
    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    version_id: Mapped[UUID] = mapped_column(ForeignKey("document_versions.id"))
    category: Mapped[str]
    company: Mapped[str | None]
    model: Mapped[str]
    prompt_version: Mapped[str]
    status: Mapped[str]
    reason: Mapped[str | None]
    created_at: Mapped[datetime]
    available_at: Mapped[datetime | None]
    prompt_tokens: Mapped[int | None]
    completion_tokens: Mapped[int | None]
    findings_json: Mapped[dict[str, Any] | None]


class ResearchFactRow(Base):
    __tablename__ = "research_facts"
    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    report_id: Mapped[UUID] = mapped_column(ForeignKey("research_reports.id"))
    version_id: Mapped[UUID] = mapped_column(ForeignKey("document_versions.id"))
    company: Mapped[str | None]
    fact_key: Mapped[str]
    value: Mapped[Decimal]
    unit: Mapped[str]
    period: Mapped[str]
    basis: Mapped[str]
    page: Mapped[int]
    span_start: Mapped[int]
    span_end: Mapped[int]
